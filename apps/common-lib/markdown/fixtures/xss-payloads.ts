export const XSS_CATEGORIES = [
  'スクリプト',
  'イベント属性',
  '危険なスキーム',
  'HTMLの入れ子',
  '属性の注入',
  '参照形式のリンク',
  '自動リンク',
  'IDによる上書き',
] as const;

export type XssCategory = (typeof XSS_CATEGORIES)[number];

export interface XssPayload {
  readonly category: XssCategory;
  readonly markdown: string;
}

const payloads = (
  category: XssCategory,
  markdowns: readonly string[],
): readonly XssPayload[] =>
  markdowns.map((markdown) => ({ category, markdown }));

